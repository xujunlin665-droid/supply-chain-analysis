    sale_date          DATE           NOT NULL COMMENT '日期（主键）',
    daily_gmv          DECIMAL(15,2)  NOT NULL COMMENT '当日成交金额(元)',
    daily_buyers       INT            NOT NULL COMMENT '当日成交人数',
    daily_items        INT            NOT NULL COMMENT '当日成交件数',
    daily_orders       INT            NOT NULL COMMENT '当日成交父单量',
    daily_sub_orders   INT            NOT NULL COMMENT '当日成交子单量',
    roll15_gmv         DECIMAL(15,2)  NULL COMMENT '15日滚动GMV',
    roll15_buyers      INT            NULL COMMENT '15日滚动成交人数',
