    roll15_orders      INT            NULL COMMENT '15日滚动父单量',
    roll15_sub_orders  INT            NULL COMMENT '15日滚动子单量',
    PRIMARY KEY (sale_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='每日销售总表';

