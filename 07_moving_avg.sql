-- ============================================================
-- 文件：07_moving_avg.sql
-- 功能：7日移动平均 & 当日偏离度
-- 数据：daily_sales（2026-05-08 至 2026-06-01，共25天）
--
-- 业务目的：
--   原始 daily_gmv 受运营活动影响波动剧烈（如5.20明星场+234%）
--   移动平均平滑噪音，暴露大盘真实增长趋势
--   偏离度定量标记"异常日"，剔除后才能做合理的预测和备货
-- ============================================================
select
sale_date,
daily_gmv,
-- ── 7日移动平均 ──────────────────────────────────────────
    -- ROWS BETWEEN 6 PRECEDING AND CURRENT ROW
    --   = 窗口包含"当前行 + 往前6行"，共最多7天
    --   = 数据不足7天时（前6行）自动收窄，不报错，不返回NULL
    -- 作用：把单日尖峰拉平，看趋势斜率
    -- 结果解读：
    --   5.08~5.12 均值约100万 → 大促前自然底部
    --   5.13后均值开始爬升   → 618开幕直播拉动
    --   5.29均值602万        → 预热蓄水到位
    --   5.30均值992万        → 爆发期基准线抬高
round(avg(daily_gmv) over (order by sale_date rows between 6 preceding and current row)
, 2)  as '七日移动平均值',
-- ── 当日偏离移动均值（%）────────────────────────────────
    -- 公式：(当日GMV - 7日均值) / 7日均值 × 100
    -- 正数 = 当日高于近7日均值（活动拉升 or 爆发）
    -- 负数 = 当日低于近7日均值（节后回落 or 自然低谷）
    --
    -- 关键结果解读：
    --   5.20 = +234.83% ← 520明星场（张凌赫+节日双驱动），脉冲异常
    --                      ⚠️ 做趋势预测时必须剔除此行
    --   5.30 = +205.99% ← 618大促首日爆发，属于预期内的结构性跳升
    --                      与5.20不同：这是大促节奏的必然结果，不算噪音
    --   5.21 = -29.14%  ← 明星场次日自然回落，符合"脉冲后回归"规律
    --   5.17 = -11.71%  ← 预热期正常低谷，周中效应
round(
 (daily_gmv-avg(daily_gmv) over (order by sale_date rows between 6 preceding and current row))/avg(daily_gmv) over (order by sale_date rows between 6 preceding and current row) *100
, 2) as '偏移均值_pct'
from daily_sales
order by sale_date;
