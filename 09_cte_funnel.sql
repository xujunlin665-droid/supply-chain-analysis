-- ============================================================
-- 文件：10_cte_funnel.sql
-- 功能：CTE + 四层漏斗转化率
-- 作者：徐郡临
-- 数据：product_sales（真实灵狐数据，2786条SKU）
--
-- 漏斗结构：曝光 → 点击 → 加购 → 成交
-- 业务目的：
--   识别每个SKU在哪一层漏斗流失最严重
--   高曝光低点击 → 商卡/标题问题
--   高点击低加购 → 价格或详情页问题
--   高加购低成交 → 缺少权益/优惠券刺激
-- ============================================================

-- CTE（公共表表达式）：
-- WITH ... AS (...) 相当于给子查询起一个临时名字
-- 优势：逻辑分层清晰，外层可以多次引用，比嵌套子查询可读性强
-- 执行顺序：先执行WITH内部，结果缓存为 funnel，再执行外层SELECT

-- ── 漏斗第一层：商卡点击率（CTR）────────────────────
        -- 衡量商卡吸引力：主图/标题/价格是否抓人
        -- 京东笔记本直播间参考值：优质SKU 15%~25%，低于8%需优化
-- ── 漏斗第二层：加购率 ──────────────────────────────
        -- 点击后有多少人加了购物车
        -- 衡量详情页+价格的吸引力，大促预热期重点看这层
        -- 参考值：30%~50%为健康，低于20%考虑加专享券
-- ── 漏斗第三层：加购转化率 ──────────────────────────
        -- 加购后实际下单的比例
        -- 大促爆发期这层会集中释放，低说明价格没跟上竞品
-- ── 漏斗综合：全链路转化率 ──────────────────────────
        -- 曝光到最终成交的总效率，是最终考核指标
        -- 1%~2% 属于正常范围，低于0.5% 整条链路都有问题
with funnel as(
select
product_name,
exposure_uv,
click_uv,
cart_uv,
order_uv,
round(click_uv/exposure_uv*100 , 2),
round(cart_uv/click_uv*100 , 2),
round(order_uv/cart_uv*100 , 2),
round(order_uv/exposure_uv*100 , 2)
from product_sales
where exposure_uv＞100
 )
select *
from funnel;


